import { fireEvent } from '@testing-library/react';
import { useLocation } from 'react-router-dom';
import {
  SelectedVehicleProvider,
  useSelectedVehicle,
  writeRecent,
  readRecent,
} from './vehicleSelection';

function Probe() {
  const { selectedId, setVehicle } = useSelectedVehicle();
  const loc = useLocation();
  return (
    <div>
      <span data-testid="selected">{selectedId ?? 'none'}</span>
      <span data-testid="search">{loc.search}</span>
      <button type="button" onClick={() => setVehicle('v2')}>
        pick-v2
      </button>
    </div>
  );
}

function renderProvider(path: string) {
  return renderPage(
    path,
    <SelectedVehicleProvider userId="u1">
      <Probe />
    </SelectedVehicleProvider>,
  );
}

describe('SelectedVehicleProvider', () => {
  beforeEach(() => {
    localStorage.clear();
  });

  it('selects the vehicle from the ?vehicle= URL param', async () => {
    renderProvider('/overview?vehicle=v9');
    const el = await screen.findByTestId('selected');
    await waitFor(() => expect(el.textContent).toBe('v9'));
  });

  it('renders no selection when there is no URL param and no recents', async () => {
    renderProvider('/overview');
    const el = await screen.findByTestId('selected');
    await waitFor(() => expect(el.textContent).toBe('none'));
  });

  it('falls back to the most recent per-device pick', async () => {
    writeRecent('u1', 'v3');
    renderProvider('/overview');
    const el = await screen.findByTestId('selected');
    await waitFor(() => expect(el.textContent).toBe('v3'));
  });

  it('updates the selection, URL param, and recents when picking a vehicle', async () => {
    renderProvider('/overview');
    await screen.findByTestId('selected');
    fireEvent.click(screen.getByText('pick-v2'));
    await waitFor(() => expect(screen.getByTestId('selected').textContent).toBe('v2'));
    expect(screen.getByTestId('search').textContent).toContain('vehicle=v2');
    expect(readRecent('u1')[0]).toBe('v2');
  });
});
