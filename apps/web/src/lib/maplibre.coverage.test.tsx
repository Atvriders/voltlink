import { setWorkerUrl } from 'maplibre-gl';
import { configureMapLibre, prefersReducedMotion, hasWebGL2 } from './maplibre';

describe('mapLibre configuration module', () => {
  it('reports the reduced-motion preference from matchMedia', async () => {
    const original = window.matchMedia;
    const queries: string[] = [];
    window.matchMedia = ((query: string) => {
      // web-9: record the REAL query and answer only the exact one — the old
      // mock answered any query containing the substring, so a wrong media
      // string still passed.
      queries.push(query);
      const matches = query === '(prefers-reduced-motion: reduce)';
      return {
        matches,
        media: query,
        onchange: null,
        addListener: () => undefined,
        removeListener: () => undefined,
        addEventListener: () => undefined,
        removeEventListener: () => undefined,
        dispatchEvent: () => false,
      } as unknown as MediaQueryList;
    }) as unknown as typeof window.matchMedia;

    expect(prefersReducedMotion()).toBe(true);
    expect(queries).toContain('(prefers-reduced-motion: reduce)');

    window.matchMedia = original;
  });

  it('defaults to no reduced motion when matchMedia is unavailable', async () => {
    const original = window.matchMedia;
    // @ts-expect-error simulate environments without matchMedia
    window.matchMedia = undefined;

    expect(prefersReducedMotion()).toBe(false);

    window.matchMedia = original;
  });

  it('configures the MapLibre worker URL exactly once', async () => {
    configureMapLibre();
    configureMapLibre();

    expect(vi.mocked(setWorkerUrl)).toHaveBeenCalledTimes(1);
    expect(vi.mocked(setWorkerUrl)).toHaveBeenCalledWith('/assets/maplibre-gl-worker-test.js');
  });

  it('renders inside a React tree and re-exports WebGL2 detection', async () => {
    function Probe() {
      configureMapLibre();
      return <div data-testid="maplibre-probe">maplibre-ready</div>;
    }

    renderPage('/map', <Probe />);

    await waitFor(() => {
      expect(screen.getByTestId('maplibre-probe')).toBeTruthy();
    });
    expect(await screen.findByText('maplibre-ready')).toBeTruthy();
    expect(typeof hasWebGL2).toBe('function');
    expect(hasWebGL2()).toBe(true);
  });
});
