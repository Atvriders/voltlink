function renderPage(path: string, ui: React.ReactNode) {
  const qc = new QueryClient({
    defaultOptions: { queries: { retry: false } },
  });
  return render(
    <QueryClientProvider client={qc}>
      <MemoryRouter initialEntries={[path]}>
        <Routes>
          <Route path="*" element={ui as React.ReactElement} />
        </Routes>
      </MemoryRouter>
    </QueryClientProvider>,
  );
}

afterEach(cleanup);

import PresentationPage from './PresentationPage';
import { fireEvent } from '@testing-library/react';

beforeEach(() => {
  Object.assign(vehicle, { make: 'VoltLink', model: 'Model One', year: 2025 });

  if (!window.matchMedia) {
    Object.defineProperty(window, 'matchMedia', {
      writable: true,
      value: (query: string) => ({
        matches: false,
        media: query,
        onchange: null,
        addListener: () => {},
        removeListener: () => {},
        addEventListener: () => {},
        removeEventListener: () => {},
        dispatchEvent: () => false,
      }),
    });
  }

  if (!window.ResizeObserver) {
    window.ResizeObserver = class {
      observe() {}
      unobserve() {}
      disconnect() {}
    } as unknown as typeof ResizeObserver;
  }

  if (!window.IntersectionObserver) {
    window.IntersectionObserver = class {
      observe() {}
      unobserve() {}
      disconnect() {}
      takeRecords() {
        return [];
      }
    } as unknown as typeof IntersectionObserver;
  }
});

describe('PresentationPage', () => {
  it('renders the demo vehicle presentation scene', async () => {
    renderPage('/presentation', <PresentationPage />);

    expect(await screen.findByText('Aurora')).toBeTruthy();
    await waitFor(() => {
      expect(screen.getByText('VoltLink')).toBeTruthy();
    });
  });

  it('falls back to the fictional vehicle when no demo vehicles exist', async () => {
    apiMock.mockImplementation(async (path: string) => {
      if (path === '/api/v1/vehicles') return [];
      return {};
    });

    renderPage('/presentation', <PresentationPage />);

    expect(await screen.findByText('VoltLink One')).toBeTruthy();
  });

  it('toggles automatic scene cycling between pause and resume', async () => {
    renderPage('/presentation', <PresentationPage />);

    const pauseButton = await screen.findByLabelText('Pause cycling');
    fireEvent.click(pauseButton);

    expect(await screen.findByLabelText('Resume cycling')).toBeTruthy();
  });

  it('labels the odometer as Odometer, not Efficiency (NEW-14)', async () => {
    renderPage('/presentation', <PresentationPage />);
    await screen.findByText('Aurora');
    // The stats scene comes up after the 12s cycle.
    await waitFor(() => expect(screen.getByText('Odometer')).toBeTruthy(), { timeout: 14000 });
    expect(screen.queryByText('Efficiency')).toBeNull();
  });
});
